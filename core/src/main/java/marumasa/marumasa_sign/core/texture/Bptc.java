            b[2] |= bs.bits(1) << 4;       /* by[4]   */
            g[0] |= bs.bits(8);        /* gw[7:0] */
            b[2] |= bs.bits(1) << 5;       /* by[5]   */
            g[2] |= bs.bits(1) << 4;       /* gy[4]   */
            b[0] |= bs.bits(8);        /* bw[7:0] */
            b[3] |= bs.bits(1) << 5;       /* bz[5]   */
