    /**
     * BC7 のブロックを展開する。out には 16 画素分の ARGB を、行ごとに並べて書く。
     */
    static void bc7(byte[] data, int pos, int[] out) {
        final Bits bs = new Bits(data, pos);
        int mode = 0;
        while (mode < 8 && bs.bits(1) == 0) mode++;
        if (mode >= 8) {
            // 不正なモードは透明な黒にする
            java.util.Arrays.fill(out, 0);
            return;
        }

        int partition = 0;
        int numPartitions = 1;
        int rotation = 0;
        int indexSelection = 0;
        if (mode == 0 || mode == 1 || mode == 2 || mode == 3 || mode == 7) {
            numPartitions = (mode == 0 || mode == 2) ? 3 : 2;
            partition = bs.bits(mode == 0 ? 4 : 6);
        }
        final int numEndpoints = numPartitions * 2;
        if (mode == 4 || mode == 5) {
            rotation = bs.bits(2);
            if (mode == 4) indexSelection = bs.bits(1);
        }

        final int[][] endpoints = new int[6][4];
        for (int c = 0; c < 3; c++) {
            for (int e = 0; e < numEndpoints; e++) {
                endpoints[e][c] = bs.bits(BC7_BITS[0][mode]);
            }
        }
        if (BC7_BITS[1][mode] > 0) {
            for (int e = 0; e < numEndpoints; e++) {
                endpoints[e][3] = bs.bits(BC7_BITS[1][mode]);
            }
        }

        final boolean hasPBits = ((BC7_HAS_PBITS >> mode) & 1) != 0;
        if (hasPBits) {
            for (int e = 0; e < numEndpoints; e++) {
                for (int c = 0; c < 4; c++) endpoints[e][c] <<= 1;
            }
            if (mode == 1) {
                // 2 つの部分で 1 ビットずつ共有する
                final int p0 = bs.bits(1);
                final int p1 = bs.bits(1);
                for (int c = 0; c < 3; c++) {
                    endpoints[0][c] |= p0;
                    endpoints[1][c] |= p0;
                    endpoints[2][c] |= p1;
                    endpoints[3][c] |= p1;
                }
            } else {
                for (int e = 0; e < numEndpoints; e++) {
                    final int p = bs.bits(1);
                    for (int c = 0; c < 4; c++) endpoints[e][c] |= p;
                }
            }
        }

        for (int e = 0; e < numEndpoints; e++) {
            // 上位のビットを下位にも繰り返して 8 ビットにする
            int precision = BC7_BITS[0][mode] + (hasPBits ? 1 : 0);
            for (int c = 0; c < 3; c++) {
                endpoints[e][c] = endpoints[e][c] << (8 - precision);
                endpoints[e][c] = endpoints[e][c] | (endpoints[e][c] >> precision);
            }
            precision = BC7_BITS[1][mode] + (hasPBits ? 1 : 0);
            endpoints[e][3] = endpoints[e][3] << (8 - precision);
            endpoints[e][3] = endpoints[e][3] | (endpoints[e][3] >> precision);
        }
        if (BC7_BITS[1][mode] == 0) {
            for (int e = 0; e < numEndpoints; e++) endpoints[e][3] = 0xFF;
        }

        final int indexBitsBase = (mode == 0 || mode == 1) ? 3 : (mode == 6 ? 4 : 2);
        final int indexBits2 = mode == 4 ? 3 : (mode == 5 ? 2 : 0);
        final int[] weights = indexBitsBase == 2 ? WEIGHT2 : (indexBitsBase == 3 ? WEIGHT3 : WEIGHT4);
        final int[] weights2 = indexBits2 == 2 ? WEIGHT2 : WEIGHT3;

        // 色の番号 (と、モード 4, 5 では続けて透明度の番号) が別々に並んでいるので、2 回に分けて読む
        final int[] indices = new int[16];
        for (int i = 0; i < 4; i++) {
            for (int j = 0; j < 4; j++) {
                final int set = numPartitions == 1 ? ((i | j) != 0 ? 0 : 128) : BC7_PARTITIONS[numPartitions - 2][partition][i][j];
                int indexBits = indexBitsBase;
                if ((set & 0x80) != 0) indexBits--;
                indices[i * 4 + j] = bs.bits(indexBits);
            }
        }
        for (int i = 0; i < 4; i++) {
            for (int j = 0; j < 4; j++) {
                final int set = (numPartitions == 1 ? ((i | j) != 0 ? 0 : 128) : BC7_PARTITIONS[numPartitions - 2][partition][i][j]) & 0x03;
                final int index = indices[i * 4 + j];
                final int[] e0 = endpoints[set * 2];
                final int[] e1 = endpoints[set * 2 + 1];
                int r, g, b, a;
                if (indexBits2 == 0) {
                    r = interpolate(e0[0], e1[0], weights, index);
                    g = interpolate(e0[1], e1[1], weights, index);
                    b = interpolate(e0[2], e1[2], weights, index);
                    a = interpolate(e0[3], e1[3], weights, index);
                } else {
                    final int index2 = bs.bits((i | j) != 0 ? indexBits2 : indexBits2 - 1);
                    if (indexSelection == 0) {
                        r = interpolate(e0[0], e1[0], weights, index);
                        g = interpolate(e0[1], e1[1], weights, index);
                        b = interpolate(e0[2], e1[2], weights, index);
                        a = interpolate(e0[3], e1[3], weights2, index2);
                    } else {
                        r = interpolate(e0[0], e1[0], weights2, index2);
                        g = interpolate(e0[1], e1[1], weights2, index2);
                        b = interpolate(e0[2], e1[2], weights2, index2);
                        a = interpolate(e0[3], e1[3], weights, index);
                    }
                }
                // 透明度と入れ替えて持っているチャンネルを戻す
                int swap;
                switch (rotation) {
                    case 1:
                        swap = a;
                        a = r;
                        r = swap;
                        break;
                    case 2:
                        swap = a;
                        a = g;
                        g = swap;
                        break;
                    case 3:
                        swap = a;
                        a = b;
                        b = swap;
                        break;
                    default:
                        break;
                }
                out[i * 4 + j] = (a << 24) | (r << 16) | (g << 8) | b;
            }
        }
    }
