    // 128 ビットのブロックを、下位のビットから順に読む
    private static final class Bits {
        private long low;
        private long high;

        Bits(byte[] data, int pos) {
            low = readLong(data, pos);
            high = readLong(data, pos + 8);
        }

        int bits(int count) {
            if (count == 0) return 0;
            final long mask = (1L << count) - 1;
            final int result = (int) (low & mask);
            low = (low >>> count) | ((high & mask) << (64 - count));
            high >>>= count;
            return result;
        }

        // ビットの並びを逆にして読む (BC6H の一部のモードで使う)
        int bitsReversed(int count) {
            int bits = bits(count);
            int result = 0;
            while (count-- > 0) {
                result = (result << 1) | (bits & 1);
                bits >>= 1;
            }
            return result;
        }

        private static long readLong(byte[] data, int pos) {
            long value = 0;
            for (int i = 7; i >= 0; i--) {
                value = (value << 8) | (data[pos + i] & 0xFFL);
            }
            return value;
        }
    }

    private static int extendSign(int value, int bits) {
        return (value << (32 - bits)) >> (32 - bits);
    }

    private static int transformInverse(int value, int a0, int bits, boolean signed) {
        value = (value + a0) & ((1 << bits) - 1);
        return signed ? extendSign(value, bits) : value;
    }

    private static int unquantize(int value, int bits, boolean signed) {
        if (!signed) {
            if (bits >= 15) return value;
            if (value == 0) return 0;
            if (value == ((1 << bits) - 1)) return 0xFFFF;
            return ((value << 16) + 0x8000) >> bits;
        }
        if (bits >= 16) return value;
        boolean negative = false;
        if (value < 0) {
            negative = true;
            value = -value;
        }
        int result;
        if (value == 0) {
            result = 0;
        } else if (value >= ((1 << (bits - 1)) - 1)) {
            result = 0x7FFF;
        } else {
            result = ((value << 15) + 0x4000) >> (bits - 1);
        }
        return negative ? -result : result;
    }

    private static int interpolate(int a, int b, int[] weights, int index) {
        return (a * (64 - weights[index]) + b * weights[index] + 32) >> 6;
    }

    // 16 ビットの浮動小数点数 (half) のビット列にする
    private static int finishUnquantize(int value, boolean signed) {
        if (!signed) return (value * 31) >> 6;
        value = value < 0 ? -(((-value) * 31) >> 5) : (value * 31) >> 5;
        int sign = 0;
        if (value < 0) {
            sign = 0x8000;
            value = -value;
        }
        return sign | value;
    }

    static float halfToFloat(int half) {
        final int exponent = (half >> 10) & 0x1F;
        final int mantissa = half & 0x3FF;
        final float sign = (half & 0x8000) != 0 ? -1f : 1f;
        if (exponent == 0) return sign * mantissa * (1f / (1 << 24));
        if (exponent == 31) return mantissa == 0 ? sign * Float.POSITIVE_INFINITY : Float.NaN;
        return sign * (float) Math.pow(2, exponent - 15) * (1f + mantissa / 1024f);
    }

